# მომხმარებელს შეაყვანინე რიცხვი 1–5. დაბეჭდე სიტყვებით, მაგალითად: 1 → One 2 → Two გამოიყენე if / elif / else

num = int(input("შეიყვანე რიცხვი 1-5 : "))

if num == 1:
    print("One")
elif num == 2:
    print("Two")
elif num == 3:
    print("Three")
elif num == 4:
    print("Four")
elif num == 5:
    print("Five")
else:
    print("არასწორი რიცხვი")