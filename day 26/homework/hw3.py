# შექმენი ცარიელი სია
# მომხმარებელი შეიყვანს რიცხვებს
# დაამატე რიცხვები სიაში
# როცა ჯამი გახდება 100-ზე მეტი, შეწყვიტე შეყვანა
# დაბეჭდე სია და მათი ჯამი

nums = []
total = 0

while total <= 100:
    num = int(input("შეიყვანე რიცხვი: "))
    nums.append(num)
    total += num

print("სია:" , nums)
print("ჯამი:" , total)