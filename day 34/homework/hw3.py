# 3) შექმენით ფუნქცია. შექმენით რიცხვებით სავსე სია, დაბეჭდეთ ამ სიის ყველა ლუწი ელემენტის ჯამი. გამოიყენე for ციკლი. გამოიძახეთ ფუნქცია.

def aaa():
    numbers = [2, 5, 8, 11, 14, 7, 6]
    total = 0

    for num in numbers:
        if num % 2 == 0:
            total = total + num

    print("ლუწი ელემენტების ჯამი : ", total)

aaa()