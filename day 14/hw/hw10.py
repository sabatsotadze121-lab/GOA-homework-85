# მომხმარებელს შემოატანინეთ რიცხვი, ამ 
# რიცხვის ჩათვლით შეკრიბეთ ყველა რიცხვი და გამოიტანეთ საბოლოო პასუხი.



num = int(input("შეიყვანეთ რიცხვი: "))

if num < 1:
    print(" შეიყვანეთ 1 ან მეტი."); 
else:
    total = 0
    i = 1
    while i <= num:
        total = total + i
        i = i + 1
    print(total)






